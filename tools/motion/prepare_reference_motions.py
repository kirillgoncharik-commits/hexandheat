#!/usr/bin/env python3
"""Reproduce the three pinned CMU reference-motion JSONs, without dependencies.

Source files stay in ignored assets/raw/cmu-motion by default. Downloading is
opt-in via --fetch; source and output bytes are checked against the manifest.
The source-selection study's metadata/metrics are retained as explicit pinned
templates. Every joint position/root-track sample is regenerated by BVH FK.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
from urllib.parse import urlparse
from urllib.request import Request, urlopen

from bvh_motion import BVH, loop_local, normalized_positions, vmul, vsub

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SERIES_KEYS = {"frames", "rootTrack", "loopFrames", "loopRootTrack"}


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def verify_source(raw, record):
    if len(raw) != record["sourceBytes"]:
        raise ValueError(f"{record['id']}: source byte count differs from manifest")
    if digest(raw) != record["sourceSha256"]:
        raise ValueError(f"{record['id']}: source SHA-256 differs from manifest")


def acquire_source(source_dir, record, commit, fetch):
    path = source_dir / record["sourceFile"]
    if path.exists():
        verify_source(path.read_bytes(), record)
        return path
    if not fetch:
        raise FileNotFoundError(
            f"Missing source {path}. Supply --source-dir with the pinned BVH "
            "files, or explicitly use --fetch to download them."
        )
    url = record["sourceUrl"]
    parsed = urlparse(url)
    if (parsed.scheme != "https" or parsed.hostname != "raw.githubusercontent.com"
            or f"/{commit}/" not in parsed.path):
        raise ValueError(f"{record['id']}: source URL is not pinned HTTPS GitHub raw")
    request = Request(url, headers={"User-Agent": "HexHeat-motion-reproducer/1"})
    with urlopen(request, timeout=30) as response:
        raw = response.read(record["sourceBytes"] + 1)
    verify_source(raw, record)
    source_dir.mkdir(parents=True, exist_ok=True)
    # Write only verified source data. No third-party code is downloaded/run.
    path.write_bytes(raw)
    print(f"Downloaded verified source {record['id']}")
    return path


def rounded(vector):
    return [round(value, 7) for value in vector]


def regenerate(path, record):
    bvh = BVH(path)
    metadata = record["metadataTemplate"]
    source = metadata["source"]
    sampling = metadata["sampling"]
    correction = metadata["loopCorrection"]
    if (bvh.frame_count != source["frames"] or bvh.frame_time != source["frameTime"]
            or bvh.channel_count != source["channelCount"]):
        raise ValueError(f"{record['id']}: parsed source header differs from metadata")
    fps = sampling["fps"]
    count = sampling["frameCount"]
    start = sampling["cropStartSeconds"]
    seconds = sampling["durationSeconds"]
    if (fps != 30 or count != 121 or seconds != 4
            or sampling["cropEndSeconds"] != start + seconds):
        raise ValueError(f"{record['id']}: unsupported fixed sampling contract")
    if (correction["sourceCropSeconds"] != 4
            or correction["sourceOverlapSeconds"] != .4
            or correction["outputSeconds"] != 4):
        raise ValueError(f"{record['id']}: unsupported loop correction contract")
    height = bvh.body_height()
    if height != metadata["coordinateSystem"]["bodyHeightSourceUnits"]:
        raise ValueError(f"{record['id']}: reference body-height scale differs")
    ids = bvh.named_indices
    remap = {old: new for new, old in enumerate(ids)}
    joints = [dict(name=bvh.joints[j].name,
                   parent=remap.get(bvh.joints[j].parent, -1),
                   restOffset=rounded(vmul(bvh.joints[j].offset, 1 / height)))
              for j in ids]
    if joints != metadata["joints"]:
        raise ValueError(f"{record['id']}: named hierarchy differs from metadata")

    raw_world = [bvh.at(start + i / fps) for i in range(count)]
    loop_world = [bvh.world(loop_local(
        bvh, start, i / fps,
        crop_seconds=correction["sourceCropSeconds"],
        overlap=correction["sourceOverlapSeconds"],
        output_seconds=correction["outputSeconds"],
    ))[0] for i in range(count)]

    def frames(series):
        return [[rounded(p[j]) for j in ids]
                for p in (normalized_positions(bvh, points, height)
                          for points in series)]

    def root_track(series):
        return [rounded(vmul(vsub(points[0], series[0][0]), 1 / height))
                for points in series]

    generated = dict(frames=frames(raw_world), rootTrack=root_track(raw_world),
                     loopFrames=frames(loop_world), loopRootTrack=root_track(loop_world))
    if set(record["outputKeyOrder"]) != set(metadata) | SERIES_KEYS:
        raise ValueError(f"{record['id']}: output key order/template mismatch")
    output = {key: generated[key] if key in SERIES_KEYS else metadata[key]
              for key in record["outputKeyOrder"]}
    encoded = (json.dumps(output, separators=(",", ":")) + "\n").encode("utf-8")
    if len(encoded) != record["outputBytes"] or digest(encoded) != record["outputSha256"]:
        raise ValueError(
            f"{record['id']}: regenerated output differs from the pinned reference; "
            "no output files written. Check Python/runtime and parser changes."
        )
    return encoded


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path,
                        default=REPO / "assets/raw/cmu-motion")
    parser.add_argument("--out-dir", type=Path,
                        default=REPO / "apps/web/assets/witch/reference-cycle")
    parser.add_argument("--fetch", action="store_true",
                        help="Download missing pinned BVH files, then verify hashes")
    parser.add_argument("--check", action="store_true",
                        help="Compare regenerated bytes with --out-dir; write nothing")
    args = parser.parse_args(argv)
    manifest = json.loads((HERE / "source-manifest.json").read_text())
    prepared = []
    # Verify every source and every generated result before writing any output.
    for record in manifest["clips"]:
        source = acquire_source(args.source_dir, record,
                                manifest["sourceCommit"], args.fetch)
        prepared.append((record, regenerate(source, record)))
    if args.check:
        for record, encoded in prepared:
            target = args.out_dir / record["outputFile"]
            if not target.exists() or target.read_bytes() != encoded:
                raise ValueError(f"{record['id']}: existing output differs or is missing: {target}")
            print(f"MATCH {record['id']} {record['outputSha256']}")
    else:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for record, encoded in prepared:
            target = args.out_dir / record["outputFile"]
            if not target.exists() or target.read_bytes() != encoded:
                target.write_bytes(encoded)
            print(f"REPRODUCED {record['id']} {record['outputSha256']}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, KeyError) as error:
        print(f"Motion preparation failed: {error}", file=sys.stderr)
        raise SystemExit(1)
